    /// <summary>规范给的版本 40 字节模式容量,四个纠错等级各一。</summary>
    private static readonly int[] MaxBytesAtVersion40 = [2953, 2331, 1663, 1273];

    /// <summary>照 <see cref="QrCode" /> 的私有表算出某版本 + 等级能装多少字节。</summary>
    private static int CapacityBytes(int version, QrEcc ecc)
    {
        MethodInfo method = typeof(QrCode).GetMethod("GetDataCodewords", BindingFlags.NonPublic | BindingFlags.Static)
                            ?? throw new InvalidOperationException("QrCode.GetDataCodewords is gone — update this test.");
        int codewords = (int)method.Invoke(null, [version, ecc])!;
        // 头部是 4 位模式指示符 + 字符数指示符(版本 1–9 是 8 位,10 起 16 位)。
        return ((codewords * 8) - (4 + (version <= 9 ? 8 : 16))) / 8;
    }

    private static void AssertMatrix(QrCode qr, string[] expected, string what)
    {
        Assert.AreEqual(expected.Length, qr.Size, $"{what}: 边长不对");
        for (int y = 0; y < qr.Size; y++)
        {
            char[] row = new char[qr.Size];
            for (int x = 0; x < qr.Size; x++)
            {
                row[x] = qr[x, y] ? '#' : '.';
            }
            Assert.AreEqual(expected[y], new string(row), $"{what}: 第 {y} 行不对");
        }
    }

    [TestMethod]
    public void Capacity_GrowsWithVersion_ForEveryEccLevel()
    {
        foreach (QrEcc ecc in Enum.GetValues<QrEcc>())
        {
            for (int version = 2; version <= 40; version++)
            {
                Assert.IsTrue(
                    CapacityBytes(version, ecc) > CapacityBytes(version - 1, ecc),
                    $"{ecc} 档:版本 {version} 的容量没有比 {version - 1} 大 —— 容量表抄错了");
            }
        }
    }

    [TestMethod]
    public void Capacity_AtVersion40_MatchesSpecification()
    {
        foreach (QrEcc ecc in Enum.GetValues<QrEcc>())
        {
            Assert.AreEqual(
                MaxBytesAtVersion40[(int)ecc], CapacityBytes(40, ecc), $"{ecc} 档的版本 40 容量与规范不符");
        }
    }

    [TestMethod]
    public void Encode_PicksSmallestVersionThatFits()
    {
        // 恰好装满 → 用这个版本;多一个字节 → 必须升一版。
        for (int version = 1; version < 40; version++)
        {
            int limit = CapacityBytes(version, QrEcc.Medium);
            Assert.AreEqual(version, QrCode.Encode(new string('a', limit), QrEcc.Medium).Version);
            Assert.AreEqual(version + 1, QrCode.Encode(new string('a', limit + 1), QrEcc.Medium).Version);
        }
    }

    [TestMethod]
    public void Encode_TooLong_Throws() =>
        Assert.ThrowsExactly<ArgumentException>(
            () => QrCode.Encode(new string('a', MaxBytesAtVersion40[(int)QrEcc.High] + 1), QrEcc.High));

    [TestMethod]
    public void Encode_ProducesSpecifiedFunctionPatterns()
    {
        // 与数据无关的那些格子:三个定位图形的中心、时序图形的交替、恒深色模块。
        foreach (string text in new[] { "a", "https://t.me/velashell_bot?startgroup=true", new string('q', 500) })
        {
            QrCode qr = QrCode.Encode(text);
            foreach ((int cx, int cy) in new[] { (3, 3), (qr.Size - 4, 3), (3, qr.Size - 4) })
            {
                for (int dy = -4; dy <= 4; dy++)
                {
                    for (int dx = -4; dx <= 4; dx++)
                    {
                        int x = cx + dx;
                        int y = cy + dy;
                        if (x < 0 || x >= qr.Size || y < 0 || y >= qr.Size)
                        {
                            continue;
                        }
                        int distance = Math.Max(Math.Abs(dx), Math.Abs(dy));
                        Assert.AreEqual(distance is not (2 or 4), qr[x, y], $"定位图形 ({x},{y}) 不对");
                    }
                }
            }
            for (int i = 8; i < qr.Size - 8; i++)
            {
                Assert.AreEqual(i % 2 == 0, qr[6, i], $"竖向时序图形第 {i} 格不对");
                Assert.AreEqual(i % 2 == 0, qr[i, 6], $"横向时序图形第 {i} 格不对");
            }
            Assert.IsTrue(qr[8, qr.Size - 8], "恒深色模块没有落下");
        }
    }

