    public void Encode_InviteUrl_MatchesGoldenMatrix()
    {
        QrCode qr = QrCode.Encode("https://t.me/velashell_bot?startgroup=true", QrEcc.Medium);
        Assert.AreEqual(3, qr.Version);
        AssertMatrix(qr, GoldenInviteMedium, "版本 3 / M");
    }

