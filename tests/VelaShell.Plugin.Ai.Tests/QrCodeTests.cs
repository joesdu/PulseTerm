/// <summary>
/// 自研二维码编码器(<see cref="QrCode" />)的守门测试。
/// </summary>
/// <remarks>
/// <para>
/// 这类编码器错了不会抛异常,只会安静地产出一张扫不出来(或扫出别的东西)的图 ——
/// 除非拿真机去扫,否则没人看得出来。所以这里的把关分三层:
/// </para>
/// <list type="number">
/// <item><b>容量表</b>:整张表是照规范抄进来的常量,抄错一个数就会让某些版本编出废码。
/// 用"必须随版本单调递增"与"版本 40 的四档容量必须等于规范给的 2953/2331/1663/1273"
/// 两条来卡 —— 开发这份编码器时,正是单调性这一条揪出了 H 档块数表里漏抄的一个数。</item>
/// <item><b>黄金矩阵</b>:三份逐格写死的期望值,覆盖版本 1(最小)、版本 3(真实的邀请链接)
/// 与版本 16(会带版本信息块的大码)。它们不是本实现自己吐出来再回填的 ——
/// 每一份都与一个独立实现(QRCoder)的输出逐格比对过,一格不差。</item>
/// <item><b>结构不变量</b>:三个定位图形、时序图形、恒深色模块的位置由规范写死,
/// 与数据无关,任何内容都该满足。</item>
/// </list>
/// <para>
/// 编码器只做字节模式,所以对纯大写或纯数字的内容会比多模式实现多用一两个版本 ——
/// 这是刻意的取舍(见 <see cref="QrCode" /> 的注释),不是缺陷,因此这里不拿版本号去卡。
/// </para>
/// </remarks>
[TestClass]
public sealed class QrCodeTests
